// VariableSize - вывод информации о размерах
//              переменных различных типов
//
#include <cstdio>
#include <cstdlib>
#include <iostream>
#include <windows.h>
using namespace std;


int main(int nNumberofArgs, char* pszArgs[])
{
	// переводим консоль на CP1251 — ту же, что и у строк в программе
	SetConsoleCP(1251);        // кодировка ввода (работает cin)
	SetConsoleOutputCP(1251);  // кодировка вывода (работает cout)
	setlocale(LC_ALL, "Russian");

	bool			b;
	char			c;
	int				n;
	long			l;
	long long		ll;
	float			f;
	double			d;
	long double     ld;

	cout << "Размер bool			=" << sizeof b << endl;
	cout << "Размер char			=" << sizeof c << endl;
	cout << "Размер int 			=" << sizeof n << endl;
	cout << "Размер long			=" << sizeof l << endl;
	cout << "Размер long long		=" << sizeof ll << endl;
	cout << "Размер float			=" << sizeof f << endl;
	cout << "Размер double			=" << sizeof d << endl;
	cout << "Размер long double		=" << sizeof ld << endl;

	// Ожидание, позволяющее пользователю увидеть результат
	// работы программы

	cout << "Нажмите Enter для продолжения..." << endl;
	cin.ignore(10, '\n');
	cin.get();
	return 0;

    
}

